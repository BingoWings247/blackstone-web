const BY_ID = new Map(ERR_NAMES.map((n) => [joaat(n), n]));

/** ERR name for a code id, 'UNKNOWN' for 0, or null when the code isn't in the table. */
export function errName(id) {
  const n = Number(id) >>> 0;
  if (n === 0) return 'UNKNOWN';
  return BY_ID.get(n) || null;
}

/** ERR family: the second segment (GFX, MEM, STR, ...). */
export function errFamily(name) {
  const m = /^ERR_([A-Z]+)/.exec(name || '');
  return m ? m[1] : null;
}
